class RecordingResult(unittest.TextTestResult):
    """Keeps the outcome and duration of every test."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.records = []
        self._started = {}

    def startTest(self, test):
        self._started[test.id()] = time.perf_counter()
        super().startTest(test)

    def _record(self, test, status):
        elapsed = time.perf_counter() - self._started.get(test.id(), time.perf_counter())
        self.records.append({"id": test.id(), "status": status, "seconds": elapsed})

    def addSuccess(self, test):
        super().addSuccess(test)
        self._record(test, "passed")

    def addFailure(self, test, err):
        super().addFailure(test, err)
        self._record(test, "failed")

    def addError(self, test, err):
        super().addError(test, err)
        self._record(test, "error")

    def addSkip(self, test, reason):
        super().addSkip(test, reason)
        self._record(test, "skipped")


def sentence(method: str) -> str:
    words = method.removeprefix("test_").replace("_", " ")
    return words[:1].upper() + words[1:]


def git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                              text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def run_suite():
    measured = coverage.Coverage(data_file=None, source=["nextaction"], branch=True)
    measured.start()
    suite = unittest.defaultTestLoader.discover(str(ROOT / "tests"))
    runner = unittest.TextTestRunner(stream=io.StringIO(), resultclass=RecordingResult, verbosity=2)
    started = time.perf_counter()
    result = runner.run(suite)
    duration = time.perf_counter() - started
    measured.stop()
    with tempfile.TemporaryDirectory() as folder:
        path = Path(folder) / "coverage.json"
        measured.json_report(outfile=str(path))
        report = json.loads(path.read_text(encoding="utf-8"))
    return result, duration, report


def render(result, duration: float, report: dict, lang: str = "en") -> str:
    text = TEXT[lang]

    def decimal(value: float) -> str:
        return f"{value:.1f}".replace(".", "," if lang == "pt" else ".")

    counts = defaultdict(int)
    for record in result.records:
        counts[record["status"]] += 1
    total = len(result.records)
    suites = defaultdict(list)
    for record in result.records:
        module, _, method = record["id"].rpartition(".")
        suites[module.split(".")[0]].append({**record, "method": method})

    totals = report["totals"]
    coverage_detail = text["coverage_detail"].format(
        lines=f"{totals['covered_lines']}/{totals['num_statements']}",
        branches=f"{totals['covered_branches']}/{totals['num_branches']}")
    lines = [
        f"# {text['title']}",
        "",
        text["intro"].format(actions=ACTIONS_URL),
        "",
        "| | |",
        "| --- | --- |",
        f"| {text['result']} | {text['passed'].format(passed=counts['passed'], total=total)}"
        + "".join(f", {counts[s]} {text[s]}" for s in ("failed", "error", "skipped") if counts[s]) + " |",
        f"| {text['duration']} | {decimal(duration)} s |",
        f"| {text['coverage']} | **{decimal(totals['percent_covered'])}%** ({coverage_detail}) |",
        f"| {text['commit']} | `{git_commit()}` |",
        f"| {text['environment']} | Python {platform.python_version()} {text['on']} {platform.system()} |",
        f"| {text['date']} | {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC |",
        "",
        f"## {text['suites']}",
        "",
        text["suite_header"],
        "| --- | --- | --- | --- |",
    ]
    for name, records in sorted(suites.items()):
        doc = (sys.modules[name].__doc__ or "").strip().splitlines()[0]
        if lang == "pt":
            doc = SUITES_PT.get(name, doc)
        passed = sum(r["status"] == "passed" for r in records)
        icon = ICONS["passed"] if passed == len(records) else ICONS["failed"]
        lines.append(f"| [`{name}`](../tests/{name}.py) | {doc} | {len(records)} | {icon} {passed}/{len(records)} |")

    lines += ["", f"## {text['modules']}", "", text["module_header"], "| --- | --- | --- | --- | --- |"]
    for path, data in sorted(report["files"].items()):
        summary = data["summary"]
        module = Path(path).as_posix()
        lines.append(
            f"| `{module}` | {summary['num_statements']} | {summary['missing_lines']} | "
            f"{summary['covered_branches']}/{summary['num_branches']} | {summary['percent_covered']:.0f}% |"
        )

    lines += ["", f"## {text['every_test']}", ""]
    for name, records in sorted(suites.items()):
        lines += [f"### `{name}`", "", text["test_header"], "| --- | --- | --- |"]
        for record in records:
            lines.append(f"| {ICONS[record['status']]} | {sentence(record['method'])} | {record['seconds'] * 1000:.0f} ms |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, help="write the report here (default: print it)")
    parser.add_argument("--output-pt", type=Path, help="also write the report in Portuguese here")
    args = parser.parse_args()
    sys.path.insert(0, str(ROOT))
    result, duration, report = run_suite()
    markdown = render(result, duration, report)
    if args.output_pt:
        args.output_pt.write_text(render(result, duration, report, "pt") + "\n", encoding="utf-8", newline="\n")
    if args.output:
        args.output.write_text(markdown + "\n", encoding="utf-8", newline="\n")
    else:
        sys.stdout.reconfigure(encoding="utf-8")
        print(markdown)
    for failure in result.failures + result.errors:
        print(f"\nFAILED {failure[0].id()}\n{failure[1]}", file=sys.stderr)
    return 0 if result.wasSuccessful() else 1


if __name__ == "__main__":
    sys.exit(main())
