"""Play every agent against the depth-4 opponent and write the results table.

    python demos/connect4/benchmark.py --games 200

Each agent plays half its games first and half second, on seeds that never appear in the
training or test data. Results go to demos/connect4/RESULTS.md.
"""

import argparse
import math
import platform
from datetime import datetime, timezone
from pathlib import Path

from play import AGENTS, OPENING_PLIES, OPPONENT_DEPTH, REVIEW_DEPTH, TEACHER_DEPTH, run_game

HERE = Path(__file__).resolve().parent
SEED_OFFSET = 200_000
LABELS = {
    "model": f"model + policy, unsure moves reviewed by depth-{REVIEW_DEPTH} search",
    "model-teacher-review": f"model + policy, unsure moves reviewed by the depth-{TEACHER_DEPTH} teacher",
    "model-only": "model + policy, no review",
    "teacher": f"depth-{TEACHER_DEPTH} search (the teacher)",
    "strong": f"depth-{REVIEW_DEPTH} search",
    "random": "random legal column",
}


def interval(wins: int, games: int) -> str:
    """95% Wilson interval for the win rate."""
    z, p = 1.96, wins / games
    centre = (p + z * z / (2 * games)) / (1 + z * z / games)
    half = z * math.sqrt(p * (1 - p) / games + z * z / (4 * games * games)) / (1 + z * z / games)
    return f"{max(0, centre - half):.0%}–{min(1, centre + half):.0%}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--games", type=int, default=200)
    parser.add_argument("--output", type=Path, default=HERE / "RESULTS.md")
    args = parser.parse_args()
    seeds = range(SEED_OFFSET, SEED_OFFSET + args.games)

    rows = []
    for kind in AGENTS:
        results = [run_game(kind, seed, agent_first=seed % 2 == 0) for seed in seeds]
        counts = {k: sum(r["result"] == k for r in results) for k in ("won", "draw", "lost")}
        moves = sum(r["moves"] for r in results)
        rows.append({"agent": kind, **counts, "interval": interval(counts["won"], len(results)),
                     "reviews": sum(r["reviews"] for r in results) / moves})
        print(rows[-1], flush=True)

    lines = [
        "# Connect Four benchmark",
        "",
        f"{args.games} games per agent against a depth-{OPPONENT_DEPTH} alpha-beta search, half playing first, each starting "
        f"from {OPENING_PLIES} random opening moves that are the same for every agent on a seed. Seeds "
        f"{seeds.start}–{seeds.stop - 1} (never used for training or test data). Generated by "
        f"`python demos/connect4/benchmark.py --games {args.games}` on {datetime.now(timezone.utc):%Y-%m-%d} "
        f"(Python {platform.python_version()}).",
        "",
        "| Agent | Wins | Draws | Losses | Win rate | 95% interval | Moves reviewed |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        *[f"| {LABELS[r['agent']]} | {r['won']} | {r['draw']} | {r['lost']} | {r['won'] / args.games:.0%} | "
          f"{r['interval']} | {r['reviews']:.1%} |" for r in rows],
        "",
        "**Moves reviewed**: share of the agent's moves where the model's confidence was below the policy "
        "threshold and a search chose instead.",
    ]
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"saved {args.output}")


if __name__ == "__main__":
    main()
