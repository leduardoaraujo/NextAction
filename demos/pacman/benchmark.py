"""Play many unseen games with every agent and write the results table.

    python demos/pacman/benchmark.py --games 300

Benchmark seeds never overlap the training or test seeds used by generate_data.py. Results
go to demos/pacman/RESULTS.md.
"""

import argparse
import math
import platform
from datetime import datetime, timezone
from pathlib import Path

from play import AGENTS, run_game

HERE = Path(__file__).resolve().parent
BENCHMARK_SEED_OFFSET = 200_000
LABELS = {
    "model": "model + policy, expert on low confidence",
    "model-only": "model + policy, alone",
    "raw": "model alone, no policy",
    "expert": "rule-based expert",
    "random": "random legal move",
}


def interval(wins: int, games: int) -> str:
    """95% Wilson interval for the win rate."""
    if not games:
        return "-"
    z, p = 1.96, wins / games
    centre = (p + z * z / (2 * games)) / (1 + z * z / games)
    half = z * math.sqrt(p * (1 - p) / games + z * z / (4 * games * games)) / (1 + z * z / games)
    return f"{max(0, centre - half):.0%}–{min(1, centre + half):.0%}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--games", type=int, default=300)
    parser.add_argument("--output", type=Path, default=HERE / "RESULTS.md")
    args = parser.parse_args()
    seeds = range(BENCHMARK_SEED_OFFSET, BENCHMARK_SEED_OFFSET + args.games)

    rows = []
    for kind in AGENTS:
        results = [run_game(kind, seed) for seed in seeds]
        steps = sum(r["steps"] for r in results)
        wins = sum(r["status"] == "won" for r in results)
        rows.append({
            "agent": kind, "wins": wins, "interval": interval(wins, len(results)),
            "score": sum(r["score"] for r in results) / len(results),
            "steps": steps / len(results),
            "reviews": sum(r["reviews"] for r in results) / steps,
            "corrections": sum(r["corrections"] for r in results) / len(results),
        })
        print(rows[-1], flush=True)

    lines = [
        "# Pac-Man benchmark",
        "",
        f"{args.games} games per agent on seeds {seeds.start}–{seeds.stop - 1}, which never appear in training "
        f"or test data. Generated by `python demos/pacman/benchmark.py --games {args.games}` on "
        f"{datetime.now(timezone.utc):%Y-%m-%d} (Python {platform.python_version()}).",
        "",
        "| Agent | Win rate | 95% interval | Avg. score | Avg. steps | Moves decided by the expert | Policy corrections per game |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| {LABELS[row['agent']]} | {row['wins'] / args.games:.0%} | {row['interval']} | {row['score']:.0f} | "
            f"{row['steps']:.0f} | {row['reviews']:.1%} | {row['corrections']:.2f} |"
        )
    lines += [
        "",
        "- **Moves decided by the expert**: share of moves where the model's confidence was below the policy "
        "threshold, so the expert (the game's stand-in for a human reviewer) chose instead.",
        "- **Policy corrections**: moves where the model's own top choice was a wall or a cell next to a ghost "
        "and the policy blocked it.",
    ]
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"saved {args.output}")


if __name__ == "__main__":
    main()
